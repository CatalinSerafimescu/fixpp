#!/usr/bin/env python3
"""tools/quickfix_enum_golden/regen_and_diff.py — 075 T009.

Local-only, out-of-CI regeneration-and-diff driver for the QuickFIX
enum-domain golden (FR-024 item 3). Guarded behind the CMake target
`quickfix_enum_golden_regen_diff`, itself only defined when
`FIXPP_BUILD_QUICKFIX_GOLDEN=ON` (a locally built QuickFIX v1.16.0 is
present) — never runs in CI by construction (the CMake target does not
exist unless a human explicitly opted in).

What it does:
  1. Snapshot the checked-in golden.csv bytes.
  2. Run the (already-built) quickfix_enum_golden generator, which
     regenerates golden.csv IN PLACE against the real, locally built
     QuickFIX.
  3. Diff the regenerated bytes against the snapshot.
  4. No drift -> exit 0. Drift -> print a unified diff and exit 1, LEAVING
     the regenerated golden.csv on disk (this is a "regen", not a
     dry-run check) so a human can inspect it, decide whether the drift is
     a real QuickFIX-version-driven divergence (T009's whole purpose --
     this is the ONLY mechanism that can catch that; the CI manifest gate,
     T007, provably cannot: it has no QuickFIX to compare against) and
     `git diff` / commit the update, or investigate further before touching
     anything.

This target is bound to the per-release interop-run checklist
(specs/016-interop-harness/quickstart.md Sec 3 "Full gate (release-prep)")
-- run it on every release-interop pass; treat a diff as a
RELEASE-BLOCKING finding, not a routine update.

Usage:
    python3 tools/quickfix_enum_golden/regen_and_diff.py \\
        --binary build/<preset>/bin/quickfix_enum_golden \\
        --golden tools/quickfix_enum_golden/golden.csv
"""
import argparse
import difflib
import subprocess
import sys


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", required=True, help="path to the built quickfix_enum_golden executable")
    parser.add_argument("--golden", required=True, help="path to tools/quickfix_enum_golden/golden.csv")
    args = parser.parse_args()

    with open(args.golden, "r", encoding="utf-8") as f:
        before = f.read()

    print(f"[regen-and-diff] snapshotting {args.golden} ({len(before)} bytes)")
    print(f"[regen-and-diff] running {args.binary} (regenerates golden.csv against real QuickFIX)")

    result = subprocess.run([args.binary], capture_output=True, text=True)
    sys.stdout.write(result.stdout)
    sys.stderr.write(result.stderr)
    if result.returncode != 0:
        print(f"[regen-and-diff] FATAL: generator exited {result.returncode}", file=sys.stderr)
        return result.returncode

    with open(args.golden, "r", encoding="utf-8") as f:
        after = f.read()

    if before == after:
        print("[regen-and-diff] no drift -- golden.csv is byte-identical to the regenerated output. GREEN.")
        return 0

    print("[regen-and-diff] DRIFT DETECTED -- the checked-in golden.csv no longer matches a fresh run "
          "against the locally built QuickFIX. This is RELEASE-BLOCKING (T009): investigate whether this "
          "is a genuine QuickFIX-version-driven behavior change (a newer QuickFIX than 1.16.0, a dictionary "
          "edit, or a generator-source change) before committing the regenerated file.", file=sys.stderr)
    diff = difflib.unified_diff(
        before.splitlines(keepends=True),
        after.splitlines(keepends=True),
        fromfile=f"{args.golden} (checked-in)",
        tofile=f"{args.golden} (regenerated)",
    )
    sys.stderr.writelines(diff)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
