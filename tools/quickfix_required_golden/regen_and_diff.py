#!/usr/bin/env python3
"""tools/quickfix_required_golden/regen_and_diff.py — 079 T018.

Local-only, out-of-CI regeneration-and-diff driver for the QuickFIX
required-set parity golden (Contract 2, census-and-agreement.md). Guarded
behind the CMake target `quickfix_required_golden_regen_diff`, itself only
defined when `FIXPP_BUILD_QUICKFIX_GOLDEN=ON` (a locally built QuickFIX
v1.16.0 is present) — never runs in CI by construction (the CMake target
does not exist unless a human explicitly opted in).

What it does (mirrors tools/quickfix_enum_golden/regen_and_diff.py, 075 T009):
  1. Snapshot the checked-in golden.csv AND golden_groups.csv bytes (081
     T020 added the latter -- per-group parity golden).
  2. Run the (already-built) quickfix_required_golden generator, which
     regenerates BOTH files IN PLACE against the real, locally built
     QuickFIX.
  3. Diff the regenerated bytes against each snapshot.
  4. No drift in either file -> exit 0. Drift -> print a unified diff (per
     file) and exit 1, LEAVING the regenerated files on disk so a human can
     inspect them, decide whether the drift is a real QuickFIX-version-driven
     divergence (this is the ONLY mechanism that can catch that; the parity
     gtests, required_scope_parity_test.cpp, provably cannot — they link no
     QuickFIX) and `git diff` / commit the update, or investigate further.

This target is bound to the per-release interop-run checklist
(specs/016-interop-harness/quickstart.md Sec 3 "Full gate (release-prep)")
-- run it on every release-interop pass; treat a diff as a
RELEASE-BLOCKING finding, not a routine update.

Usage:
    python3 tools/quickfix_required_golden/regen_and_diff.py \\
        --binary build/<preset>/bin/quickfix_required_golden \\
        --golden tools/quickfix_required_golden/golden.csv
"""
import argparse
import difflib
import os
import subprocess
import sys


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", required=True, help="path to the built quickfix_required_golden executable")
    parser.add_argument("--golden", required=True, help="path to tools/quickfix_required_golden/golden.csv")
    args = parser.parse_args()

    # 081 T020: the generator also regenerates a sibling golden_groups.csv in
    # the same directory as --golden; snapshot/diff both.
    golden_groups_path = os.path.join(os.path.dirname(args.golden), "golden_groups.csv")

    snapshots = {}
    for path in (args.golden, golden_groups_path):
        with open(path, "r", encoding="utf-8") as f:
            snapshots[path] = f.read()
        print(f"[regen-and-diff] snapshotting {path} ({len(snapshots[path])} bytes)")

    print(f"[regen-and-diff] running {args.binary} (regenerates both files against real QuickFIX)")

    result = subprocess.run([args.binary], capture_output=True, text=True)
    sys.stdout.write(result.stdout)
    sys.stderr.write(result.stderr)
    if result.returncode != 0:
        print(f"[regen-and-diff] FATAL: generator exited {result.returncode}", file=sys.stderr)
        return result.returncode

    any_drift = False
    for path, before in snapshots.items():
        with open(path, "r", encoding="utf-8") as f:
            after = f.read()

        if before == after:
            print(f"[regen-and-diff] no drift -- {path} is byte-identical to the regenerated output. GREEN.")
            continue

        any_drift = True
        print(f"[regen-and-diff] DRIFT DETECTED in {path} -- the checked-in file no longer matches a fresh "
              "run against the locally built QuickFIX. This is RELEASE-BLOCKING: investigate whether this is "
              "a genuine QuickFIX-version-driven behavior change (a newer QuickFIX than 1.16.0, a dictionary "
              "edit, or a generator-source change) before committing the regenerated file.", file=sys.stderr)
        diff = difflib.unified_diff(
            before.splitlines(keepends=True),
            after.splitlines(keepends=True),
            fromfile=f"{path} (checked-in)",
            tofile=f"{path} (regenerated)",
        )
        sys.stderr.writelines(diff)

    return 1 if any_drift else 0


if __name__ == "__main__":
    raise SystemExit(main())
