namespace fixpp::codegen {

namespace {

void emit_field_ref(TemplateWriter& w, fixpp::dict::FieldRef const& r) {
    w.raw("    { ");
    w.num(r.tag);
    w.raw(", static_cast<::fixpp::dict::field_data_type>(");
    w.num(static_cast<std::uint64_t>(r.type));
    w.raw("), static_cast<::fixpp::dict::field_presence>(");
    w.num(static_cast<std::uint64_t>(r.rule));
    w.raw("), ");
    w.num(r.condition_index);
    w.raw(", ");
    w.num(r.group_no_tag);
    w.raw(", ");
    w.num(r.component_index);
    w.raw(", ");
    w.num(r.enum_table_index);
    w.raw(", ");
    w.num(r.length_pair_data_tag);
    w.raw(", 0 },");
    w.line();
}

}  // namespace

std::string emit_fields(VersionIR const& ir) {
    TemplateWriter w;
    w.line("// SPDX-License-Identifier: AGPL-3.0-or-later");
    w.line("// GENERATED by fixpp-codegen (003-dictionary-codegen, T023). DO NOT EDIT.");
    w.line("// <vXX>/Fields.hpp — constexpr FieldRef arrays (data-model Entity 2,");
    w.line("// AC-V1/AC-V2/AC-V6). Static storage, zero runtime allocation.");
    w.line("#pragma once");
    w.line("#include <fixpp/dict/field_ref.hpp>");
    w.line();
    w.raw("namespace fixpp::");
    w.raw(ir.ns);
    w.line("::fields {");
    w.line();
    for (auto const& m : ir.messages) {
        std::string const id = to_identifier(m.name);
        if (m.fields.empty()) {
            w.raw("// ");
            w.raw(id);
            w.raw(" (MsgType ");
            w.raw(m.msg_type);
            w.line(") — no declared fields; no array emitted.");
            w.line();
            continue;
        }
        w.raw("inline constexpr ::fixpp::dict::FieldRef ");
        w.raw(id);
        w.raw("_fields[] = {  // MsgType ");
        w.line(m.msg_type);
        for (auto const& f : m.fields) {
            emit_field_ref(w, f.ref);
        }
        w.line("};");
        w.line();
    }
    w.raw("}  // namespace fixpp::");
    w.raw(ir.ns);
    w.line("::fields");
    return std::move(w).take();
}

}  // namespace fixpp::codegen
