// 003-dictionary-codegen — T026 — <vXX>/NormativeReferences.md per-message
// citations (AC-V5; [const §VI.5], Appendix B; [2c §10] Q7 confirmed at
// implementation). The QuickFIX source XML carries no per-message §X.Y.Z
// section anchors (only MsgType/name); the resolvable normative citation is
// therefore the version-level FIX specification reference per [const §VI.5]
// emitted once + one row per message keyed by (Name, MsgType, [FIXxx]
// citation token). Deterministic LF-only output over the bytewise-sorted
// message list (NFR-003-7).
#include "emit.hpp"
#include "template_writer.hpp"

namespace fixpp::codegen {

namespace {

// Version-level normative reference per [const §VI.5] / Appendix B.
struct SpecRef {
    std::string_view label;     // "FIX 4.4"
    std::string_view token;     // "[FIX44]" — the per-message citation token
    std::string_view normative;  // full normative-reference line
};

SpecRef spec_ref(std::string_view ns) {
    if (ns == "v42")
        return {"FIX 4.2", "[FIX42]",
                "FIX Protocol Ltd., *Financial Information eXchange Protocol "
                "(FIX), Version 4.2*."};
    if (ns == "v44")
        return {"FIX 4.4", "[FIX44]",
                "FIX Protocol Ltd., *Financial Information eXchange Protocol "
                "(FIX), Version 4.4*."};
    if (ns == "v50sp2")
        return {"FIX 5.0 SP2", "[FIX50SP2]",
                "FIX Trading Community, *FIX 5.0 Service Pack 2* (with "
                "Extension Packs)."};
    return {"FIXT 1.1", "[FIXT11]",
            "FIX Trading Community, *FIX Transport (FIXT) 1.1*."};
}

}  // namespace

std::string emit_normative_refs(VersionIR const& ir) {
    SpecRef const sr = spec_ref(ir.ns);
    TemplateWriter w;
    w.raw("# Normative References — fixpp::");
    w.raw(ir.ns);
    w.line(" (GENERATED — DO NOT EDIT)");
    w.line();
    w.line("Generated by fixpp-codegen (003-dictionary-codegen, T026) per");
    w.line("`[const §VI.5]` / Appendix B; AC-V5. One row per emitted standard");
    w.line("message; the version-level FIX specification is the resolvable");
    w.line("normative anchor (the QuickFIX source XML carries no per-message");
    w.line("section numbers — `[2c §10]` Q7).");
    w.line();
    w.line("## Normative reference");
    w.line();
    w.raw("- ");
    w.raw(sr.token);
    w.raw(" ");
    w.line(sr.normative);
    w.line();
    w.line("## Per-message citations");
    w.line();
    w.line("| Message | MsgType | Citation |");
    w.line("|---|---|---|");
    for (auto const& m : ir.messages) {
        w.raw("| ");
        w.raw(m.name);
        w.raw(" | `");
        w.raw(m.msg_type);
        w.raw("` | ");
        w.raw(sr.token);
        w.raw(" *");
        w.raw(sr.label);
        w.raw("* |");
        w.line();
    }
    return std::move(w).take();
}

}  // namespace fixpp::codegen
