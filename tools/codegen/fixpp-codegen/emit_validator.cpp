// 003-dictionary-codegen — T025 — <vXX>/Validator.hpp per-message rule tables
// + the Length+Data pair table (data-model Entity 3; AC-V3/AC-V4/AC-V6).
// This PR emits + shape/exhaustiveness-tests the tables vs the source XML;
// behavioural validation is out of scope (spec §5). The Length+Data pair
// table is exhaustive vs source XML (every paired LENGTH tag the loaded
// Dictionary knows — ascending-tag scan in ir.cpp; AC-V4 / I-8 / seam #19).
// constexpr static storage, zero runtime allocation (I-5). std::array is used
// so a message with no fields / a version with no Length pairs emits a legal
// zero-size table (no zero-length C array). Deterministic LF-only output.
#include "emit.hpp"
#include "gen_util.hpp"
#include "template_writer.hpp"

namespace fixpp::codegen {

std::string emit_validator(VersionIR const& ir) {
    TemplateWriter w;
    w.line("// SPDX-License-Identifier: AGPL-3.0-or-later");
    w.line("// GENERATED by fixpp-codegen (003-dictionary-codegen, T025). DO NOT EDIT.");
    w.line("// <vXX>/Validator.hpp — per-message rule tables + Length+Data pair");
    w.line("// table (data-model Entity 3; AC-V3/AC-V4). Shape/exhaustiveness only;");
    w.line("// behavioural validation is out of scope (spec §5).");
    w.line("#pragma once");
    w.line("#include <fixpp/dict/field_ref.hpp>");
    w.line("#include <array>");
    w.line("#include <cstddef>");
    w.line("#include <cstdint>");
    w.line();
    w.raw("namespace fixpp::");
    w.raw(ir.ns);
    w.line("::validator {");
    w.line();
    w.line("struct rule_row {");
    w.line("    ::std::uint16_t              tag;");
    w.line("    ::fixpp::dict::field_presence rule;");
    w.line("};");
    w.line();
    w.line("struct length_data_pair {");
    w.line("    ::std::uint16_t length_tag;");
    w.line("    ::std::uint16_t data_tag;");
    w.line("};");
    w.line();
    for (auto const& m : ir.messages) {
        std::string const id = to_identifier(m.name);
        w.raw("inline constexpr ::std::array<rule_row, ");
        w.num(m.fields.size());
        w.raw("> ");
        w.raw(id);
        w.raw("_rules = {{  // MsgType ");
        w.line(m.msg_type);
        for (auto const& f : m.fields) {
            w.raw("    { ");
            w.num(f.ref.tag);
            w.raw(", static_cast<::fixpp::dict::field_presence>(");
            w.num(static_cast<std::uint64_t>(f.ref.rule));
            w.raw(") },");
            w.line();
        }
        w.line("}};");
        w.line();
    }
    w.raw("// AC-V4 / I-8 / seam #19 — exhaustive Length+Data pair table vs source XML.\n");
    w.raw("inline constexpr ::std::array<length_data_pair, ");
    w.num(ir.length_pairs.size());
    w.line("> length_data_pairs = {{");
    for (auto const& p : ir.length_pairs) {
        w.raw("    { ");
        w.num(p.length_tag);
        w.raw(", ");
        w.num(p.data_tag);
        w.raw(" },");
        w.line();
    }
    w.line("}};");
    w.line();
    w.raw("}  // namespace fixpp::");
    w.raw(ir.ns);
    w.line("::validator");
    return std::move(w).take();
}

}  // namespace fixpp::codegen
